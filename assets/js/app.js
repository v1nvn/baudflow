const chartHooks = {}

chartHooks.SpeedChart = {
  mounted() {
    const c = chartColors()
    const g = chartGridColors()
    const ctx = document.getElementById("speed-chart-canvas").getContext("2d")
    this.chart = new Chart(ctx, {
      type: "line",
      data: {
        labels: [],
        datasets: [
          {
            label: "Download (Mbps)",
            data: [],
            borderColor: c.download.border,
            backgroundColor: c.download.bg,
            fill: true,
            tension: 0.3
          },
          {
            label: "Upload (Mbps)",
            data: [],
            borderColor: c.upload.border,
            backgroundColor: c.upload.bg,
            fill: true,
            tension: 0.3
          },
          {
            label: "7d Avg",
            data: [],
            borderColor: c.avg7.border,
            borderDash: [6, 3],
            pointRadius: 0,
            fill: false
          },
          {
            label: "30d Avg",
            data: [],
            borderColor: c.avg30.border,
            borderDash: [6, 3],
            pointRadius: 0,
            fill: false
          }
        ]
      },
      options: {
        responsive: true,
        scales: {
          x: { type: "time", time: { unit: "hour" }, grid: { color: g.grid.color }, ticks: { color: g.ticks.color } },
          y: { title: { display: true, text: "Mbps", color: g.title.color }, grid: { color: g.grid.color }, ticks: { color: g.ticks.color } }
        },
        plugins: {
          tooltip: { mode: "index", intersect: false }
        }
      }
    })

    this.handleEvent("chart_data", ({results, averages}) => {
      const sorted = [...results].reverse()
      this.chart.data.labels = sorted.map(r => r.timestamp)
      this.chart.data.datasets[0].data = sorted.map(r => r.download_mbps)
      this.chart.data.datasets[1].data = sorted.map(r => r.upload_mbps)

      // Overlay: flat 7d/30d average lines spanning the full time range
      if (sorted.length > 0 && averages) {
        this.chart.data.datasets[2].data = sorted.map(() => averages.avg_7d)
        this.chart.data.datasets[3].data = sorted.map(() => averages.avg_30d)
      }

      this.chart.update()
    })

    this.handleEvent("append_point", ({point}) => {
      this.chart.data.labels.push(point.timestamp)
      this.chart.data.datasets[0].data.push(point.download_mbps)
      this.chart.data.datasets[1].data.push(point.upload_mbps)

      // Keep overlay lines in sync with data length
      const len = this.chart.data.labels.length
      const avg7 = this.chart.data.datasets[2].data[0] ?? null
      const avg30 = this.chart.data.datasets[3].data[0] ?? null
      this.chart.data.datasets[2].data = Array(len).fill(avg7)
      this.chart.data.datasets[3].data = Array(len).fill(avg30)

      this.chart.update()
    })

    watchTheme(this.chart)
  }
}

